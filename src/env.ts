import { mkdirSync } from "node:fs";
import { connect } from "node:net";
import { dirname, join } from "node:path";
import { dek, decrypt, PREFIX } from "./secrets";
import type { Config, Instance, State } from "./state";

export const ports = (c: Config, slot: number) =>
  Object.fromEntries(Object.entries(c.ports ?? {}).map(([k, p]) => [k, p + slot * (c.step ?? 10)]));

// a test listen() misses sockets bound to 127.0.0.1 only on macOS, so ask whether anyone answers instead
// ponytail: a service bound only to a LAN ip is not detected
const answers = (port: number, host: string) =>
  new Promise<boolean>((ok) => {
    const s = connect(port, host)
      .once("connect", () => (s.destroy(), ok(true)))
      .once("error", () => ok(false));
  });
export const isFree = async (port: number) => !(await answers(port, "127.0.0.1")) && !(await answers(port, "::1"));

/** Lowest slot not taken by another instance whose ports are all free right now. */
export async function allocSlot(c: Config, s: State) {
  const used = new Set(Object.values(s.instances).map((i) => i.slot));
  for (let slot = 1; ; slot++) {
    if (used.has(slot)) continue;
    const ps = Object.values(ports(c, slot));
    if (ps.some((p) => p > 65535)) throw new Error("no free slot left");
    if ((await Promise.all(ps.map(isFree))).every(Boolean)) return slot;
  }
}

const quote = (v: string) => (/^[\w.:/@+,-]*$/.test(v) ? v : JSON.stringify(v));

/** Render every [env."<file>"] table into <instance>/<file>. */
export async function writeEnv(name: string, i: Instance, c: Config) {
  const ctx: Record<string, string> = { name, slot: String(i.slot) };
  for (const [k, p] of Object.entries(ports(c, i.slot))) ctx[`ports.${k}`] = String(p);
  const fill = (v: string) =>
    v.replace(/\{\{\s*([\w.-]+)\s*\}\}/g, (_, k: string) => {
      if (!(k in ctx)) throw new Error(`unknown template variable {{${k}}}`);
      return ctx[k]!;
    });

  let key: Uint8Array | undefined;
  const reveal = async (v: string) => (v.startsWith(PREFIX) ? decrypt(v, (key ??= await dek(i.path))) : v);

  for (const [file, vars] of Object.entries(c.env ?? {})) {
    const lines = await Promise.all(
      Object.entries(vars).map(async ([k, v]) => `${k}=${quote(fill(await reveal(String(v))))}`),
    );
    const out = join(i.path, file);
    mkdirSync(dirname(out), { recursive: true });
    await Bun.write(out, `# generated by bgbng, edit bgbng.toml instead\n${lines.join("\n")}\n`);
    if (Bun.spawnSync(["git", "check-ignore", "-q", file], { cwd: i.path }).exitCode !== 0)
      console.warn(`warning: ${file} is not gitignored, decrypted secrets could get committed`);
  }
}
